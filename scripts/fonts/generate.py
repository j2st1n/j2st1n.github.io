"""Regenerate committed webfont assets from the frozen character partition.

Run from any directory with Python and scripts/fonts/requirements.txt installed.
Normal Astro builds use the committed output and need neither Python nor network.
"""

import hashlib
import io
import json
import subprocess
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "public/fonts/kami-cn.woff2"
GROUPS = Path(__file__).with_name("kami-groups.json")
OUTPUT = ROOT / "public/fonts/kami"
STYLES = ROOT / "src/styles/kami-fonts.css"
MANIFEST = ROOT / "src/generated/kami-fonts.json"
CJK_RANGES = (
    (0x2E80, 0x2FFF), (0x3000, 0x303F), (0x3100, 0x312F),
    (0x31A0, 0x31EF), (0x3400, 0x4DBF), (0x4E00, 0x9FFF),
    (0xF900, 0xFAFF), (0xFE30, 0xFE4F), (0xFF00, 0xFFEF),
    (0x20000, 0x2FA1F),
)


def unicode_range(codepoints):
    """Use exact, non-overlapping ranges so unused chunks stay unloaded."""
    result = []
    for point in sorted(codepoints):
        if result and point == result[-1][1] + 1:
            result[-1][1] = point
        else:
            result.append([point, point])
    return ",".join(
        f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
        for start, end in result
    )


def main():
    source_bytes = SOURCE.read_bytes()
    original = TTFont(io.BytesIO(source_bytes))
    original_points = set(original.getBestCmap())
    groups = json.loads(GROUPS.read_text())["groups"]
    points = [ord(char) for group in groups for char in group["characters"]]
    if len(points) != len(set(points)) or set(points) != original_points:
        raise ValueError("Partition must cover every original codepoint exactly once")

    OUTPUT.mkdir(parents=True, exist_ok=True)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    styles = ["/* Generated by scripts/fonts/generate.py; do not edit. */"]
    manifest = {
        "sourceSha256": hashlib.sha256(source_bytes).hexdigest(),
        "sourceBytes": len(source_bytes),
        "codepoints": len(points),
        "chunks": [],
    }
    expected_files = set()
    for group in groups:
        codepoints = set(map(ord, group["characters"]))
        font = TTFont(io.BytesIO(source_bytes), recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ["*"]
        options.notdef_outline = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)
        font.flavor = "woff2"
        data = io.BytesIO()
        font.save(data)
        data = data.getvalue()
        fingerprint = hashlib.sha256(data).hexdigest()[:12]
        filename = f"{group['id']}-{fingerprint}.woff2"
        expected_files.add(filename)
        (OUTPUT / filename).write_bytes(data)
        url = f"/fonts/kami/{filename}"
        ranges = unicode_range(codepoints)
        manifest["chunks"].append({
            "id": group["id"], "url": url, "bytes": len(data),
            "unicodeRange": ranges,
        })
        aliases = [("TsangerJinKai02", codepoints)]
        cjk = {p for p in codepoints if any(start <= p <= end for start, end in CJK_RANGES)}
        if cjk:
            aliases.append(("TsangerJinKai02 Code CJK", cjk))
        for family, covered in aliases:
            styles.append(
                f'@font-face {{\n  font-family: "{family}";\n'
                f'  src: url("{url}") format("woff2");\n'
                '  font-style: normal;\n  font-weight: 400 500;\n'
                f'  font-display: swap;\n  unicode-range: {unicode_range(covered)};\n}}'
            )

    # Only prune this generator's dedicated output, never the source or other fonts.
    for old in OUTPUT.glob("*.woff2"):
        if old.name not in expected_files:
            old.unlink()
    STYLES.write_text("\n\n".join(styles) + "\n")
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n")
    subprocess.run(
        [str(ROOT / "node_modules/.bin/prettier"), "--write", str(STYLES), str(MANIFEST)],
        check=True,
        stdout=subprocess.DEVNULL,
    )
    print(f"Generated {len(groups)} chunks; all {len(points)} original codepoints retained")


if __name__ == "__main__":
    main()
