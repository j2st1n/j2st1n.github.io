"""Add verified Han coverage to the webfont without rebuilding the base chunks."""

import argparse
import hashlib
import io
import re
from pathlib import Path
from tempfile import NamedTemporaryFile

from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

from generate import ROOT, SOURCE, unicode_range

STYLES = ROOT / "src/styles/kami-extra.css"


def existing_points():
    if not STYLES.exists():
        return set()
    css = STYLES.read_text()
    path = re.search(r'url\("/fonts/(kami-extra-[0-9a-f]{12}\.woff2)"\)', css)
    if path is None:
        raise ValueError("Could not read the previous supplement asset path")
    previous = ROOT / "public/fonts" / path[1]
    with TTFont(previous) as font:
        return set(font.getBestCmap())


def glyph_shape(font, point):
    glyphs = font.getGlyphSet()
    glyph = glyphs[font.getBestCmap()[point]]
    pen = DecomposingRecordingPen(glyphs)
    glyph.draw(pen)
    return glyph.width, pen.value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Official full W04 font file")
    parser.add_argument("characters", help="Additional Han characters to include")
    args = parser.parse_args()
    existing = existing_points()
    with TTFont(SOURCE) as base:
        points = (existing | set(map(ord, args.characters))) - set(base.getBestCmap())
    if not points:
        parser.error("No additional characters to include")
    font = TTFont(args.source, recalcTimestamp=False)
    if font["name"].getDebugName(6) != "TsangerJinKai02-W04":
        parser.error("The supplement must use the same W04 font weight as the site")
    unsupported = points - set(font.getBestCmap())
    if unsupported:
        parser.error(f"Full W04 lacks: {unicode_range(unsupported)}")

    shapes = {point: glyph_shape(font, point) for point in points}
    subsetter = subset.Subsetter()
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    font.flavor = "woff2"
    output = io.BytesIO()
    font.save(output)
    data = output.getvalue()
    with TTFont(io.BytesIO(data)) as rendered:
        if set(rendered.getBestCmap()) != points or any(
            glyph_shape(rendered, point) != shape for point, shape in shapes.items()
        ):
            raise ValueError("Supplement glyph coverage, outline or advance changed")

    digest = hashlib.sha256(data).hexdigest()[:12]
    asset = ROOT / "public/fonts" / f"kami-extra-{digest}.woff2"
    ranges = unicode_range(points).replace(",", ", ")
    styles = ["/* Generated by scripts/fonts/supplement.py. */"]
    for family in ("TsangerJinKai02", "TsangerJinKai02 Code CJK"):
        styles.append(
            f'@font-face {{\n  font-family: "{family}";\n'
            f'  src: url("/fonts/{asset.name}") format("woff2");\n'
            "  font-style: normal;\n  font-weight: 400 500;\n"
            f"  font-display: swap;\n  unicode-range: {ranges};\n}}"
        )
    if not asset.exists() or asset.read_bytes() != data:
        asset.write_bytes(data)
    # Keep earlier fingerprints available to pages with the previous stylesheet.
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=STYLES.parent, delete=False) as output:
        output.write("\n\n".join(styles) + "\n")
    temporary = Path(output.name)
    try:
        temporary.chmod(0o644)
        temporary.replace(STYLES)
    finally:
        temporary.unlink(missing_ok=True)
    print(f"Verified {len(points)} supplemental characters, {len(data)} bytes")


if __name__ == "__main__":
    main()
